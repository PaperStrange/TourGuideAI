#!/usr/bin/env node
/**
 * sync-block-doors.mjs — keep the door inventory in step with doors.json.
 *
 * THE DEFECT THIS CLOSES. `evidence/tools/block-doors.json` is UPSTREAM of
 * `attestations/block-doors.json` — merge-pack-meta.mjs reads the former at line 35 and publishes
 * the latter on every build. When task-20 cut the south side from 5 doors to 3, the inventory here
 * still listed all 12. Editing only the published copy would have LOOKED correct and silently
 * reverted on the next build, because the build regenerates its output from this stale source.
 *
 * The Lead's card listed the fields where they are visible; this is where they are durable.
 *
 * THE FIX, and why it is shaped this way. `doors.json` is the AUTHORITY for which doors exist —
 * `doors-author` owns it and `validate-doors.mjs` asserts it. So the inventory's count and doorIds
 * are now GENERATED from it here rather than hand-maintained, which means they cannot drift again.
 * `places.json`'s declared doorIds are deliberately NOT copied into this file: the two are also
 * compared against each other by validate-city-pack-v2.mjs check (G), and a second copy here would
 * turn a real disagreement into a silent agreement.
 *
 * The human-written prose (the building ids, the field-ownership map, the why) is left alone — only
 * the two machine checkable fields are rebuilt.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PACK = resolve(HERE, '../..');
const readJson = (p, f) => (existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : f);

const doors = readJson(resolve(PACK, 'doors.json'), { doors: [] });
const authority = doors.doors.map((d) => d.doorId);

const inventoryPath = resolve(HERE, 'block-doors.json');
const inv = readJson(inventoryPath, null);
if (!inv) { console.error('sync-block-doors: evidence/tools/block-doors.json is missing'); process.exit(1); }

const before = { count: inv.count, doorIds: JSON.stringify(inv.doorIds ?? []) };
inv.count = authority.length;
inv.doorIds = authority;
// Record the derivation so a reader does not mistake these for hand-curated values.
inv.derivedFrom = {
  count: 'doors.json doors[].doorId — regenerated by evidence/tools/sync-block-doors.mjs on every build',
  doorIds: 'doors.json doors[].doorId — regenerated by evidence/tools/sync-block-doors.mjs on every build',
  notDerived: 'every other field in this file is hand-written',
  why: 'This file used to carry a hand-maintained list, and it went stale the moment task-20 cut the south side from 5 doors to 3. Because merge-pack-meta.mjs publishes attestations/block-doors.json FROM this file, the staleness would have reverted a correct downstream fix on the next build.',
};

const changed = before.count !== inv.count || before.doorIds !== JSON.stringify(inv.doorIds);
if (changed) writeFileSync(inventoryPath, JSON.stringify(inv, null, 2) + '\n', 'utf8');

const south = authority.filter((d) => d.startsWith('D-S'));
const north = authority.filter((d) => d.startsWith('D-N'));
console.log(`sync-block-doors: ${authority.length} doors (${north.length} north, ${south.length} south: ${south.join(' ')}) — ${changed ? `updated from count=${before.count}, ${before.doorIds}` : 'already in step'}`);
