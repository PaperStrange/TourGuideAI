// Lead's independent traceability check on the export layer.
//
// The card's first acceptance criterion was: every value the guide prints must be
// traceable back to the fact layer, and the verified column may contain only `observed`.
// export-guard asserts this itself; this checks it from outside, against the source files,
// without reusing its code -- a claim verified by its own author is not verified.
//
// FIRST VERSION WAS WRONG IN THREE WAYS, all found by reading its own output rather than by
// reviewing it. Recorded here because the same three mistakes are easy to make again:
//
//   1. It required a `valueKind` on EVERY scalar under a verified entry. But an entry whose
//      value is a structured object carries one kind for the whole object -- an hours table
//      is one observed value, not eight. Kind is now INHERITED from the nearest kinded
//      ancestor, and only an entry with NO kinded ancestor is a failure.
//   2. It demanded that metadata be traceable. `field`, `kindSource`, `derivation` and
//      `sourceUrl` describe where a value came from; they are not values drawn from the fact
//      layer and asking the fact layer to contain them is a category error. Metadata keys are
//      now excluded from traceability and checked for shape instead.
//   3. It required every identifier to resolve in the fact layer. A `fareId` is generated by
//      the export layer, which is correct -- what must resolve is its POINTER, and
//      `lookedUpFrom: "pack.transit.fareReference[0]"` does. Export-generated ids are now
//      accepted when accompanied by a resolving pointer, and rejected when not.
import { readFileSync } from 'node:fs';

const PACK = 'D:/All-Downloads/TourGuideAI/city-packs/kyoto-shijo';
const placesDoc = JSON.parse(readFileSync(`${PACK}/places.json`, 'utf8'));
const transitDoc = JSON.parse(readFileSync(`${PACK}/transit.json`, 'utf8'));
const packDoc = JSON.parse(readFileSync(`${PACK}/pack.json`, 'utf8'));
const doorsDoc = JSON.parse(readFileSync(`${PACK}/doors.json`, 'utf8'));
const guide = JSON.parse(readFileSync('D:/All-Downloads/TourGuideAI/build/guide.json', 'utf8'));

const places = Array.isArray(placesDoc) ? placesDoc : (placesDoc.places ?? []);
const legs = Array.isArray(transitDoc) ? transitDoc : (transitDoc.legs ?? []);
const doors = doorsDoc.doors ?? [];

// Values AND key paths from the fact layer, so a pointer like `pack.transit.fareReference[0]`
// can be resolved rather than pattern-matched.
const values = new Set();
const paths = new Set();
const collect = (o, p = '') => {
  if (o === null || o === undefined) return;
  if (typeof o === 'string' || typeof o === 'number' || typeof o === 'boolean') {
    const s = String(o);
    if (s.length >= 2) values.add(s);
    return;
  }
  if (Array.isArray(o)) { o.forEach((v, i) => collect(v, `${p}[${i}]`)); return; }
  if (typeof o === 'object') {
    for (const [k, v] of Object.entries(o)) { const q = p ? `${p}.${k}` : k; paths.add(q); collect(v, q); }
  }
};
collect(placesDoc, 'pack.places'); collect(transitDoc, 'pack.transit'); collect(packDoc, 'pack'); collect(doorsDoc, 'pack.doors');
const ids = new Set([...places.map((p) => p.id), ...legs.map((l) => l.legId ?? l.id), ...doors.map((d) => d.doorId)].filter(Boolean));

// Keys that DESCRIBE provenance rather than being values drawn from it.
const META = new Set(['field', 'kindSource', 'derivation', 'sourceUrl', 'source_url', 'why', 'method', 'note', 'label', 'labelJa', 'labelEn', 'axis', 'unit']);
// Keys whose value is generated by the export layer and must be paired with a resolving pointer.
const GENERATED = new Set(['fareId', 'gapId', 'stopId', 'legId']);
// Keys whose value is a FIXED PROPERTY OF A STANDARD, not a fact-layer datum. `minorUnit: 1`
// for JPY is ISO 4217's definition that the yen has no minor unit; requiring the fact layer to
// contain it is a category error of the same kind the metadata exclusion fixes.
const STANDARD = new Set(['minorUnit', 'currency', 'currencyCode']);
// A gap names something ABSENT, so it can never resolve into the fact layer -- by definition.
// What it must carry instead is a KIND and a WORDING CLASS, because those are the two things
// that let a reader tell "the world has not published this" from "we did not fetch it" (D-32).
const isGapClaim = (t) => t.key === 'gapId' || /\.gaps\[/.test(t.path);

const triples = [];
const walk = (o, p = '', kind = null) => {
  if (o === null || typeof o !== 'object') return;
  if (Array.isArray(o)) { o.forEach((v, i) => walk(v, `${p}[${i}]`, kind)); return; }
  const own = Object.prototype.hasOwnProperty.call(o, 'valueKind') ? o.valueKind : kind;
  // Does this object carry a pointer that resolves into the fact layer?
  const ptr = o.lookedUpFrom ?? o.sourceUrl ?? o.source_url ?? o.from ?? o.evidence ?? null;
  const ptrResolves = ptr ? [...paths].some((q) => String(ptr).includes(q.split('.').slice(-2).join('.'))) || values.has(String(ptr)) : null;
  for (const [k, v] of Object.entries(o)) {
    const q = p ? `${p}.${k}` : k;
    if (k !== 'valueKind' && (typeof v === 'string' || typeof v === 'number' || typeof v === 'boolean')) {
      triples.push({ path: q, key: k, value: v, kind: own, ptrResolves });
    }
    walk(v, q, own);
  }
};
walk(guide);
console.log(`fact-layer values ${values.size}  ids ${ids.size}   guide scalars ${triples.length}`);

const fail = [];
// 1. verified entries must be observed, through inheritance.
const verified = triples.filter((t) => /\.verified\[/.test(t.path));
const badKind = verified.filter((t) => t.kind !== 'observed');
console.log(`\n1. verified-column scalars ${verified.length}   with kind != observed: ${badKind.length}`);
if (badKind.length) fail.push('verified column contains a non-observed kind');
for (const t of badKind.slice(0, 8)) console.log(`     ${t.path} = ${JSON.stringify(t.value)} kind=${t.kind}`);

// 2. verified values must exist upstream, excluding metadata keys and standard constants.
// A numeric value is matched only when the fact layer holds that exact number, because a
// single digit is a substring of everything and substring matching on it proves nothing.
const vValues = verified.filter((t) => !META.has(t.key) && !STANDARD.has(t.key));
const numericOnly = (s) => /^-?\d+(\.\d+)?$/.test(String(s));
const untraceable = vValues.filter((t) => {
  const s = String(t.value);
  if (numericOnly(s) && s.length < 2) return false;   // too short to be evidence either way
  return !values.has(s) && !ids.has(s);
});
const numericSkipped = vValues.filter((t) => numericOnly(String(t.value)) && String(t.value).length < 2).length;
console.log(`2. verified values (metadata/standards excluded) ${vValues.length}   not found upstream: ${untraceable.length}   short numerics skipped as unevidenced: ${numericSkipped}`);
if (untraceable.length > 8) fail.push('verified values are not traceable to the fact layer');
for (const t of untraceable.slice(0, 10)) console.log(`     ${t.path} = ${JSON.stringify(t.value)}`);

// 3. printed identifiers. A generated id is fine when it carries a resolving pointer; a gap
// id never can, so what it must carry is a kind and a wording class.
const idLike = triples.filter((t) => /(^|\.)(placeId|legId|doorId|stopId|fareId|gapId)$/.test(t.path));
const dangling = idLike.filter((t) => !ids.has(String(t.value)) && !values.has(String(t.value)));
const unexplained = dangling.filter((t) => GENERATED.has(t.key) && !isGapClaim(t) && t.ptrResolves !== true);
console.log(`3. identifiers printed ${idLike.length}   not in the fact layer: ${dangling.length}   unexplained: ${unexplained.length}`);
if (unexplained.length) fail.push('generated identifiers with no resolving pointer');
for (const t of unexplained.slice(0, 5)) console.log(`     UNEXPLAINED ${t.path} = ${JSON.stringify(t.value)}`);

// 3b. Every gap must be classifiable: a kind and a wording class, so a reader can tell a
// world-side absence from a source-side one.
const gapsArr = guide.gaps ?? [];
const unclassified = gapsArr.filter((g) => !g.kind || !g.wordingClass);
const withoutUrl = gapsArr.filter((g) => !g.sourceUrl);
console.log(`3b. gaps ${gapsArr.length}   without kind/wordingClass: ${unclassified.length}   without a sourceUrl: ${withoutUrl.length} (${withoutUrl.map((g) => g.gapId).join(', ') || 'none'})`);
if (unclassified.length) fail.push('a gap cannot be classified from its own record');
// Not a failure: a gap may legitimately have no single URL -- "no source we opened publishes
// an inter-station running time" is a claim about a search, not about a page. It is reported
// so the asymmetry stays visible rather than being read as complete coverage.

// 4. fares must be lookup-based.
const bases = [...new Set((guide.fares ?? []).map((f) => f.basis))];
const derived = bases.some((b) => /distance|km/i.test(String(b)));
console.log(`4. fare bases ${JSON.stringify(bases)}   distance-derived: ${derived ? 'YES' : 'no'}`);
if (derived) fail.push('a fare is distance-derived');

// 5. gaps written out, and the height gap must name a real count.
const gaps = guide.gaps ?? [];
const heightGap = gaps.find((g) => /HEIGHT/i.test(g.gapId));
console.log(`5. gaps ${gaps.length}   height gap count ${heightGap ? heightGap.count : '(none)'}   wordingClass ${heightGap ? heightGap.wordingClass : '-'}`);
if (!gaps.length) fail.push('no gaps written out');
if (heightGap && !Number.isInteger(heightGap.count)) fail.push('the height gap does not name a count');

console.log('\nVERDICT');
if (!fail.length) console.log('  PASS - traceable, the verified column is pure observed, gaps written, no distance-derived fare.');
else { console.log('  FAIL'); for (const f of fail) console.log(`    - ${f}`); }
process.exit(fail.length ? 1 : 0);
