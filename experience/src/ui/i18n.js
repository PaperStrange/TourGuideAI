/** Return plain interface text; callers choose how to safely render it. */
export function t(locale, key, vars = {}) {
  const catalog = String(locale).toLowerCase().startsWith('zh') ? UI.zh : UI.en;
  const template = Object.hasOwn(catalog, key) ? catalog[key] : UI.en[key];
  if (typeof template !== 'string') return String(key);
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    Object.hasOwn(vars, name) ? String(vars[name]) : match,
  );
}
