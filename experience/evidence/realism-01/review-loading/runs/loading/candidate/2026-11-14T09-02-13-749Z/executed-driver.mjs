async function servePackage() {
  const verifiedFiles = [];
  for (const expected of report.packageManifest.files) {
    const filename = resolve(packageDirectory, expected.path);
    assert(filename.startsWith(packageDirectory + sep), 'Manifest path must remain inside the package');
    const bytes = readFileSync(filename);
    assert.equal(bytes.length, expected.bytes, `Package size: ${expected.path}`);
    assert.equal(sha(bytes), expected.sha256, `Package hash: ${expected.path}`);
    verifiedFiles.push({ path: expected.path, bytes: bytes.length, sha256: sha(bytes) });
  }
  report.packageIdentity = { manifestSha256: sha(readFileSync(resolve(packageDirectory, 'package-manifest.json'))),
    verifiedFiles, verified: true };
  persist();
  const compressed = new Map();
  server = createServer((request, response) => {
    const pathname = decodeURIComponent(new URL(request.url, 'http://localhost').pathname);
    if (pathname === '/favicon.ico') { response.writeHead(204); response.end(); return; }
    const filename = resolve(packageDirectory, pathname.slice(1));
    if (!filename.startsWith(packageDirectory + sep) || !existsSync(filename) || !statSync(filename).isFile()) {
      response.writeHead(404); response.end(); return;
    }
    if (['.html', '.js', '.css', '.json', '.svg'].includes(extname(filename))) {
      if (!compressed.has(filename)) compressed.set(filename, gzipSync(readFileSync(filename), { level: 9 }));
      const bytes = compressed.get(filename);
      response.writeHead(200, { 'Content-Type': mime[extname(filename)], 'Content-Encoding': 'gzip',
        'Content-Length': bytes.length, 'Cache-Control': 'no-store' }); response.end(bytes); return;
    }
    response.writeHead(200, { 'Content-Type': mime[extname(filename)] || 'application/octet-stream',
      'Content-Length': statSync(filename).size, 'Cache-Control': 'no-store' });
    const stream = createReadStream(filename);
    stream.on('error', error => response.destroy(error));
    response.on('close', () => stream.destroy()); stream.pipe(response);
  });
  await new Promise((accept, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', accept);
  });
  return `http://127.0.0.1:${server.address().port}/index.html`;
}

function transferAt(boundary) {
  const requests = report.network.filter(item => item.startedAt <= boundary).map(item => {
    const complete = Number.isFinite(item.finishedAt) && item.finishedAt <= boundary;
    const received = Number.isFinite(item.responseAt) && item.responseAt <= boundary;
    const laterEncodedBytes = item.data.filter(event => event.timestamp <= boundary)
      .reduce((total, event) => total + event.encodedDataLength, 0);
    const bytes = complete ? item.totalEncodedBytes : (received ? item.initialEncodedPrefixBytes : 0) + laterEncodedBytes;
    return { requestId: item.requestId, url: item.url, complete, bytes };
  });
  return { boundary, totalEncodedBytes: requests.reduce((total, item) => total + item.bytes, 0),
    inflightBytes: requests.filter(item => !item.complete).reduce((total, item) => total + item.bytes, 0), requests };
}

async function pollUntil(predicate, label) {
  const deadline = Date.now() + timeout;
  while (Date.now() < deadline) {
    const state = await snapshot(page);
    if (state?.status === 'error') throw new Error(`Runtime error during ${label}: ${state.error}`);
    if (predicate(state)) return state;
    await page.waitForTimeout(100);
  }
  report.timeout = { label, view: await snapshot(page) }; persist();
  throw new Error(`Timed out waiting for ${label}`);
}

async function settle() {
  return pollUntil(view => view?.drawnView?.paging?.settled && view.drawnSplats > 0
    && sameCamera(view, view.drawnView) && !view.requests.some(request => request.status === 'pending'), 'settled source camera');
}

async function probe(action, phase) {
  const before = await snapshot(page);
  const startedAt = await page.evaluate(() => performance.now());
  await page.locator(`[data-action="${action}"]`).click();
  const input = await page.evaluate(({ action, startedAt }) => window.__LOADING_OBSERVATIONS__.inputs
    .findLast(item => item.action === action && item.at >= startedAt), { action, startedAt });
  assert(input?.trusted, 'Probe requires an observed trusted input event');
  const requested = await snapshot(page);
  const after = await pollUntil(view => view?.drawnView?.frames > before.frames
    && !sameCamera(before.drawnView, view.drawnView) && sameCamera(view, view.drawnView), `${phase} ${action}`);
  const sample = { action, phase, startedAt, input, submittedAt: after.drawnView.submittedAt,
    inputToSubmittedMs: after.drawnView.submittedAt - input.at,
    automationStartToSubmittedMs: after.drawnView.submittedAt - startedAt, before, requested, after };
  report.probes.push(sample);
  check(`${phase}-${action}-submitted`, !sameCamera(before.drawnView, after.drawnView), sample);
}

async function reset(reference) {
  const before = await snapshot(page);
  await page.locator('[data-action="reset"]').click();
  return pollUntil(view => view?.drawnView?.frames > before.frames && sameCamera(view, view.drawnView)
    && sameCamera(reference, view), 'reset camera draw');
}

async function capture(name) {
  const before = await settle();
  const bytes = await page.locator('#review-canvas').screenshot({ path: resolve(output, `${name}.png`), type: 'png', timeout });
  const after = await snapshot(page);
  const record = { path: `${name}.png`, bytes: bytes.length, sha256: sha(bytes), before, after };
  report.captures.push(record);
  check(`${name}-stable`, sameCamera(before, after) && before.drawnSplats === after.drawnSplats
    && after.drawnView.paging.settled, { before: before.drawnView, after: after.drawnView });
  return record;
}

async function compareImages(left, leftPath, right, rightPath, id) {
  const images = [leftPath, rightPath].map(filename => `data:image/png;base64,${readFileSync(filename).toString('base64')}`);
  const metrics = await page.evaluate(async urls => {
    const images = [];
    for (const url of urls) {
      const bitmap = await createImageBitmap(await (await fetch(url)).blob());
      const canvas = new OffscreenCanvas(bitmap.width, bitmap.height);
      const context = canvas.getContext('2d', { willReadFrequently: true });
      context.drawImage(bitmap, 0, 0);
      const rgba = context.getImageData(0, 0, bitmap.width, bitmap.height).data;
      images.push({ width: bitmap.width, height: bitmap.height, rgba }); bitmap.close();
    }
    if (images[0].width !== images[1].width || images[0].height !== images[1].height) throw new Error('Image dimensions differ');
    const histogram = new Array(256).fill(0);
    let total = 0, maximum = 0, alphaMismatches = 0, differingRgbChannels = 0;
    for (let index = 0; index < images[0].rgba.length; index++) {
      const difference = Math.abs(images[0].rgba[index] - images[1].rgba[index]);
      if (index % 4 === 3) { if (difference) alphaMismatches++; continue; }
      histogram[difference]++; total += difference; maximum = Math.max(maximum, difference);
      if (difference) differingRgbChannels++;
    }
    const channels = images[0].width * images[0].height * 3;
    let count = 0, p95ChannelError = 0;
    for (let value = 0; value < histogram.length; value++) {
      count += histogram[value]; if (count >= Math.ceil(channels * .95)) { p95ChannelError = value; break; }
    }
    return { width: images[0].width, height: images[0].height, maxChannelError: maximum, p95ChannelError,
      meanAbsoluteError255: total / channels, differingRgbChannels, alphaMismatches };
  }, images);
  const matched = sameCamera(left.before, right.before) && left.before.drawnSplats === right.before.drawnSplats;
  const comparison = { id, ...metrics, sameCameraAndCount: matched, referencePath: leftPath, candidatePath: rightPath,
    criteria: { maxChannelError: 1, p95ChannelError: 0, alphaMismatches: 0, source: 'D25' } };
  (report.imageComparisons ??= []).push(comparison);
  check(`${id}-exact-pixels`, metrics.differingRgbChannels === 0 && metrics.alphaMismatches === 0, comparison, 'diagnostic');
  check(id, matched && metrics.maxChannelError <= 1 && metrics.p95ChannelError === 0 && metrics.alphaMismatches === 0, comparison);
}

